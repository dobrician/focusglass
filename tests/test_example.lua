-- lua tests/test_example.lua
-- Checks that the settings file runs the plugin only while Omarchy lists it as
-- enabled, and that, when it is off, it deletes only a shader focusglass wrote.

local dir = arg[0]:match("^(.*)/tests/") or "."
local example = dir .. "/examples/focusglass.lua"
local sandbox = os.tmpname()
os.remove(sandbox)

local failures = 0
local function check(cond, msg)
  if not cond then failures = failures + 1; print("FAIL: " .. msg) else print("ok:   " .. msg) end
end
local function write(path, text)
  os.execute("mkdir -p '" .. path:match("^(.*)/") .. "'")
  local f = assert(io.open(path, "w")); f:write(text); f:close()
end
local function exists(path)
  local f = io.open(path); if f then f:close() end
  return f ~= nil
end

-- A stand-in plugin that only says it was run.
write(sandbox .. "/.config/omarchy/plugins/dc.focusglass/hypr/focusglass.lua",
  'return { setup = function() print("SETUP") end }')

local shader = sandbox .. "/.config/hypr/shaders/surface.frag"
local function run(shell_json)
  if shell_json then write(sandbox .. "/.config/omarchy/shell.json", shell_json)
  else os.remove(sandbox .. "/.config/omarchy/shell.json") end
  local p = io.popen("HOME='" .. sandbox .. "' lua -e 'hl = { exec_cmd = function(c) print(\"EXEC \" .. c) end }' '"
    .. example .. "' 2>&1")
  local out = p:read("a"); p:close()
  return out
end

local enabled = '{ "disabledPlugins": ["omarchy.battery"], "plugins": [ { "id": "a.b" }, {\n "id": "dc.focusglass"\n } ], "version": 1 }'
local disabled = '{ "disabledPlugins": ["dc.focusglass"], "plugins": [ { "id": "a.b" } ], "version": 1 }'
local ours = "#version 300 es\n// Generated by focusglass 0.1.0 from Hyprland's own surface shader.\n"

write(shader, ours)
local out = run(enabled)
check(out:find("SETUP", 1, true), "enabled: runs the plugin")
check(exists(shader), "enabled: leaves the shader to the plugin")

out = run(disabled)
check(not out:find("SETUP", 1, true), "disabled: does not run the plugin")
check(not exists(shader), "disabled: deletes the focusglass shader")
check(out:find("EXEC hyprctl reloadshaders", 1, true), "disabled: reloads shaders")

out = run(disabled)
check(not out:find("EXEC", 1, true), "disabled, no shader: does nothing")

write(shader, "#version 300 es\n// my own shader\n")
out = run(disabled)
check(exists(shader), "disabled: keeps a shader it did not write")

out = run(nil)
check(not out:find("SETUP", 1, true), "no shell.json: does not run the plugin")

os.execute("rm -rf '" .. sandbox .. "'")
if failures > 0 then print(failures .. " failed"); os.exit(1) end
print("all passed")
