-- focusglass: keeps your attention on the active window.
--
-- Every window that loses focus fades to grayscale, gets darker, slightly frosted
-- and see-through, so the one you work in is the only one that stands out.
--
-- Hyprland has no per-window color filter, so focusglass reuses the one per-window
-- value its surface shader already gets: the dim tint of an inactive window.
-- It writes a patched copy of Hyprland's own surface shader to
-- ~/.config/hypr/shaders/surface.frag (Hyprland prefers that file over the built-in
-- one), in which the dim tint drives grayscale, darkness and blur instead of plain
-- darkening. The patch is made from the shader of the Hyprland you have installed,
-- so it follows Hyprland updates; if a future shader no longer matches, focusglass
-- removes its copy and tells you, and Hyprland draws windows as usual.
--
-- Load it from your config (see examples/focusglass.lua):
--
--   local focusglass = dofile(".../dc.focusglass/hypr/focusglass.lua")
--   focusglass.setup({ darkness = 40 })

local M = {}

M.VERSION = "0.1.3"

M.DEFAULTS = {
  enabled         = true,
  grayscale       = 100,  -- % of color removed from inactive windows (0 = keep colors)
  darkness        = 50,   -- % of brightness removed from inactive windows (0 = as bright as the active one)
  transparency    = 45,   -- % see-through for inactive windows (0 = opaque)
  blur            = 12,   -- % frost on the content of inactive windows (0 = sharp, 100 = unreadable)
  background_blur = true, -- blur what shows through transparent windows (Hyprland's own blur)
  exempt_key      = "SUPER + BACKSPACE", -- keep one window normal; false to leave the key alone
}

-- Hyprland sends the shader tint = 1 - dim. focusglass sets dim_strength to this
-- value, so the shader can turn the tint back into "how inactive is this window"
-- (0 to 1), which also follows Hyprland's fadeDim animation.
M.DIM_STRENGTH = 0.15

-- blur = 100 means a frost radius of this many pixels
M.MAX_BLUR_PX = 10

M.MARKER = "// Generated by focusglass"

local HOME       = os.getenv("HOME") or ""
local SHADER_DIR = HOME .. "/.config/hypr/shaders"
local OVERRIDE   = SHADER_DIR .. "/surface.frag"
local UPSTREAM   = "/usr/include/hyprland/src/render/shaders/surface.frag.inc"
local VERSION_H  = "/usr/include/hyprland/src/version.h"
local STATE_DIR  = (os.getenv("XDG_STATE_HOME") or (HOME .. "/.local/state")) .. "/focusglass"

local PLUGIN_DIR = (debug.getinfo(1, "S").source:match("^@(.*)/hypr/[^/]+$")) or "."
local SETTINGS   = HOME .. "/.config/hypr/focusglass.lua"
local SHELL_JSON = HOME .. "/.config/omarchy/shell.json"

-- The settings file of focusglass 0.1.0 loaded this module without checking
-- whether the plugin is enabled. setup() swaps these lines for the current ones.
local PREAMBLE_0_1_0 = [[
local plugin = (os.getenv("HOME") or "") .. "/.config/omarchy/plugins/dc.focusglass/hypr/focusglass.lua"
local ok, focusglass = pcall(dofile, plugin)
if not ok then return end -- the plugin was removed: nothing to do
]]

-- ---------------------------------------------------------------------------
-- helpers

local function read(path)
  local f = io.open(path, "r")
  if not f then return nil end
  local s = f:read("a")
  f:close()
  return s
end

local function shell_quote(s)
  return "'" .. tostring(s):gsub("'", "'\\''") .. "'"
end

-- Writes to a temporary file next to path and renames it over path only when
-- every byte was written, so a full disk never leaves path half written.
local function write(path, content)
  -- follow a symlink (a dotfiles setup), so the link stays and its target changes
  local p = io.popen("readlink -f -- " .. shell_quote(path) .. " 2>/dev/null")
  local real = p and p:read("l")
  if p then p:close() end
  if real and real ~= "" then path = real end
  local tmp = path .. ".tmp-focusglass"
  local f, err = io.open(tmp, "w")
  if not f then return false, err end
  local ok, werr = f:write(content)
  local closed, cerr = f:close()
  if not ok or not closed then
    os.remove(tmp)
    return false, werr or cerr
  end
  local renamed, rerr = os.rename(tmp, path)
  if not renamed then
    os.remove(tmp)
    return false, rerr
  end
  return true
end

-- Tells the user something once per distinct message, so a config reload loop
-- doesn't flood the notification center.
local function notify_once(key, title, body)
  local stamp = STATE_DIR .. "/notified-" .. key
  if read(stamp) == body then return end
  os.execute("mkdir -p " .. shell_quote(STATE_DIR))
  write(stamp, body)
  if hl and hl.exec_cmd then
    hl.exec_cmd("notify-send -a focusglass " .. shell_quote(title) .. " " .. shell_quote(body))
  end
end

local function replace_once(s, old, new)
  local i, j = s:find(old, 1, true)
  if not i or s:find(old, j + 1, true) then return nil end
  return s:sub(1, i - 1) .. new .. s:sub(j + 1)
end

local function num(v)
  return string.format("%.4f", v)
end

-- ---------------------------------------------------------------------------
-- settings

-- Merges user settings over the defaults and checks them. Returns the settings
-- and a list of problems (each one already corrected to a usable value).
function M.resolve(user)
  local s, problems = {}, {}
  for k, v in pairs(M.DEFAULTS) do s[k] = v end

  for k, v in pairs(user or {}) do
    if M.DEFAULTS[k] == nil then
      problems[#problems + 1] = string.format("unknown setting '%s'", tostring(k))
    else
      s[k] = v
    end
  end

  for _, k in ipairs({ "grayscale", "darkness", "transparency", "blur" }) do
    local v = s[k]
    if type(v) ~= "number" then
      problems[#problems + 1] = string.format("'%s' must be a number from 0 to 100, using %d", k, M.DEFAULTS[k])
      s[k] = M.DEFAULTS[k]
    elseif v < 0 or v > 100 then
      problems[#problems + 1] = string.format("'%s' must be from 0 to 100, got %s", k, tostring(v))
      s[k] = math.max(0, math.min(100, v))
    end
  end

  for _, k in ipairs({ "enabled", "background_blur" }) do
    if type(s[k]) ~= "boolean" then
      problems[#problems + 1] = string.format("'%s' must be true or false", k)
      s[k] = M.DEFAULTS[k]
    end
  end

  if s.exempt_key ~= false and type(s.exempt_key) ~= "string" then
    problems[#problems + 1] = "'exempt_key' must be a key combination like \"SUPER + BACKSPACE\" or false"
    s.exempt_key = M.DEFAULTS.exempt_key
  end

  return s, problems
end

-- ---------------------------------------------------------------------------
-- shader

-- Takes Hyprland's surface.frag source and returns the focusglass version, or
-- nil and a reason when the source doesn't look like the shader it was written for.
function M.patch(src, s)
  local grayscale  = s.grayscale / 100
  local brightness = 1 - s.darkness / 100
  local radius     = s.blur / 100 * M.MAX_BLUR_PX

  local header = table.concat({
    M.MARKER .. " " .. M.VERSION .. " from Hyprland's own surface shader. Do not edit:",
    "// it is rewritten from your focusglass settings at every config reload.",
    "// Delete it (and run `hyprctl reloadshaders`) to get Hyprland's shader back.",
    "",
  }, "\n")

  local defs = table.concat({
    "#if USE_TINT",
    "// focusglass settings",
    "const float FG_DIM_STRENGTH = " .. num(M.DIM_STRENGTH) .. ";",
    "const float FG_GRAYSCALE    = " .. num(grayscale) .. ";",
    "const float FG_BRIGHTNESS   = " .. num(brightness) .. ";",
    "const float FG_BLUR_RADIUS  = " .. num(radius) .. "; // in texture pixels",
    "const int   FG_BLUR_TAPS    = 48;",
    "",
    "// how inactive the window is, 0 to 1 (follows the fadeDim animation)",
    "float fgAmount(vec3 t) {",
    "    return clamp((1.0 - t.r) / FG_DIM_STRENGTH, 0.0, 1.0);",
    "}",
    "",
    "vec3 fgColor(vec3 c, vec3 t) {",
    "    float amount = fgAmount(t);",
    "    float luma   = dot(c, vec3(0.2126, 0.7152, 0.0722));",
    "    return mix(c, vec3(luma), amount * FG_GRAYSCALE) * mix(1.0, FG_BRIGHTNESS, amount);",
    "}",
    "#endif",
    "",
    "",
  }, "\n")

  local frost = table.concat({
    "#if USE_TINT && !USE_MOTION_BLUR",
    "    // focusglass: frost the content of an inactive window",
    "    if (FG_BLUR_RADIUS > 0.0) {",
    "        float frost = fgAmount(tint);",
    "        if (frost > 0.0) {",
    "            vec2  px   = FG_BLUR_RADIUS * frost / vec2(textureSize(tex, 0));",
    "            vec4  acc  = vec4(0.0);",
    "            float wsum = 0.0;",
    "            for (int i = 0; i < FG_BLUR_TAPS; i++) {",
    "                float r   = sqrt((float(i) + 0.5) / float(FG_BLUR_TAPS));",
    "                float th  = float(i) * 2.39996323;",
    "                vec2  off = vec2(cos(th), sin(th)) * r * px;",
    "                float w   = 1.0 - 0.5 * r;",
    "#if USE_RGBA",
    "                acc += texture(tex, v_texcoord + off) * w;",
    "#else",
    "                acc += vec4(texture(tex, v_texcoord + off).rgb, 1.0) * w;",
    "#endif",
    "                wsum += w;",
    "            }",
    "            pixColor = acc / wsum;",
    "        }",
    "    }",
    "#endif",
    "",
    "",
  }, "\n")

  local out = src

  -- header right after the #version line, which must stay first
  local nl = out:find("\n", 1, true)
  if not nl or not out:sub(1, nl):match("^#version") then
    return nil, "the shader does not start with #version"
  end
  out = out:sub(1, nl) .. header .. out:sub(nl + 1)

  local steps = {
    { "layout(location = 0) out vec4 fragColor;", defs .. "layout(location = 0) out vec4 fragColor;", true },
    { "#if USE_DISCARD && !USE_BLUR\n", frost .. "#if USE_DISCARD && !USE_BLUR\n", true },
    { "pixColor.rgb = pixColor.rgb * tint;", "pixColor.rgb = fgColor(pixColor.rgb, tint);", true },
    { "mirrorColor.rgb = mirrorColor.rgb * tint;", "mirrorColor.rgb = fgColor(mirrorColor.rgb, tint);", false },
  }

  for _, step in ipairs(steps) do
    local patched = replace_once(out, step[1], step[2])
    if patched then
      out = patched
    elseif step[3] then
      return nil, "could not find `" .. step[1]:gsub("\n", "") .. "`"
    end
  end

  return out
end

-- Hyprland's surface shader as installed with the hyprland package, as plain GLSL.
local function upstream_shader()
  local inc = read(UPSTREAM)
  if not inc then return nil end
  return (inc:gsub('^R"#%(', ""):gsub('%)#"%s*$', ""))
end

local function installed_version()
  local h = read(VERSION_H)
  return h and h:match('GIT_TAG%s+"v?([^"]+)"')
end

local function ours(path)
  local s = read(path)
  return s ~= nil and s:find(M.MARKER, 1, true) ~= nil
end

local function remove_override()
  if ours(OVERRIDE) then
    os.remove(OVERRIDE)
    return true
  end
  return false
end

-- Writes the shader for these settings. Returns true when the effect can run.
local function install_shader(s)
  local existing = read(OVERRIDE)
  if existing and not existing:find(M.MARKER, 1, true) then
    notify_once("foreign", "focusglass is off",
      OVERRIDE .. " already exists and was not made by focusglass. Move it away to use focusglass.")
    return false
  end

  local running = hl and hl.version and hl.version() or nil
  local headers = installed_version()
  if running and headers and running:gsub("^v", "") ~= headers then
    -- Hyprland was updated but not restarted: the installed shader belongs to the
    -- new version. Keep the current file until the next login.
    return existing ~= nil
  end

  local src = upstream_shader()
  if not src then
    notify_once("noheaders", "focusglass is off", "Hyprland's shader source was not found at " .. UPSTREAM .. ".")
    return false
  end

  local shader, err = M.patch(src, s)
  if not shader then
    local removed = remove_override()
    notify_once("patch", "focusglass is off",
      "This Hyprland's window shader changed (" .. err .. "). focusglass needs an update." ..
      (removed and " Its shader was removed, windows look normal again." or ""))
    if removed and hl and hl.exec_cmd then hl.exec_cmd("hyprctl reloadshaders") end
    return false
  end

  if existing ~= shader then
    os.execute("mkdir -p " .. shell_quote(SHADER_DIR))
    local ok, werr = write(OVERRIDE, shader)
    if not ok then
      notify_once("write", "focusglass is off", "Could not write " .. OVERRIDE .. ": " .. tostring(werr))
      return false
    end
    if hl and hl.exec_cmd then hl.exec_cmd("hyprctl reloadshaders") end
  end

  return true
end

-- ---------------------------------------------------------------------------
-- enabled state and settings file

-- Omarchy lists enabled plugins in ~/.config/omarchy/shell.json; disable and
-- remove take focusglass out of that list.
function M.enabled_in_omarchy()
  local json = read(SHELL_JSON)
  local plugins = json and json:match('"plugins"%s*:%s*(%b[])')
  return plugins ~= nil and plugins:find('"id"%s*:%s*"dc%.focusglass"') ~= nil
end

-- Brings a settings file from 0.1.0 up to date, keeping the user's values: its
-- lines that load the plugin are replaced with the ones from the current
-- template, which check that the plugin is enabled first.
local function migrate_settings()
  local current = read(SETTINGS)
  if not current then return end
  local i, j = current:find(PREAMBLE_0_1_0, 1, true)
  if not i then return end
  local template = read(PLUGIN_DIR .. "/examples/focusglass.lua")
  local preamble = template and template:match("\n(local home = .-\nif not ok then return end\n)")
  if not preamble then return end
  -- The settings file is replaced only once a full copy of it is saved.
  local backup = SETTINGS .. ".bak.focusglass-0.1.0"
  local saved = read(backup)
  if saved and saved ~= current then
    backup = backup .. "-" .. os.time()
    saved = read(backup)
  end
  local ok, err = true, nil
  if saved ~= current then ok, err = write(backup, current) end
  if ok and read(backup) ~= current then ok, err = false, "the copy does not match" end
  if ok then ok, err = write(SETTINGS, current:sub(1, i - 1) .. preamble .. current:sub(j + 1)) end

  if ok then
    notify_once("migrated", "focusglass settings updated",
      SETTINGS .. " now runs focusglass only while the plugin is enabled. Your values are kept; the old file is in " .. backup .. ".")
  else
    notify_once("migrate", "focusglass settings not updated",
      "Could not update " .. SETTINGS .. " (" .. tostring(err) .. "); it was left as it was. " ..
      "focusglass still does nothing while the plugin is disabled, and tries again at the next reload.")
  end
end

-- ---------------------------------------------------------------------------
-- entry point

function M.setup(user)
  migrate_settings()

  -- A 0.1.0 settings file calls setup() even when the plugin is disabled: do
  -- nothing then, beyond giving Hyprland its own window shader back.
  if not M.enabled_in_omarchy() then
    if remove_override() and hl and hl.exec_cmd then hl.exec_cmd("hyprctl reloadshaders") end
    return nil
  end

  local s, problems = M.resolve(user)
  if #problems > 0 then
    notify_once("settings", "focusglass settings", table.concat(problems, "\n"))
  end

  if not s.enabled then
    if remove_override() and hl and hl.exec_cmd then hl.exec_cmd("hyprctl reloadshaders") end
    hl.config({ decoration = { dim_inactive = false } })
    return s
  end

  local shader_effects = s.grayscale > 0 or s.darkness > 0 or s.blur > 0
  local shader_ok = shader_effects and install_shader(s)

  local decoration = {
    -- the dim tint carries "how inactive" to the shader; without the shader it
    -- would only darken, so it stays off then
    dim_inactive     = shader_ok,
    dim_strength     = M.DIM_STRENGTH,
    inactive_opacity = 1 - s.transparency / 100,
  }
  if s.background_blur and s.transparency > 0 then
    decoration.blur = { enabled = true }
  end
  hl.config({ decoration = decoration })

  if s.exempt_key and o and o.rebind then
    o.rebind(s.exempt_key, "Keep this window normal when it loses focus (focusglass)",
      shell_quote(PLUGIN_DIR .. "/bin/focusglass-exempt"))
  end

  return s
end

return M
